CREATE EXTENSION IF NOT EXISTS postgis;

CREATE ROLE syscad_owner LOGIN PASSWORD '1234_owner';
CREATE ROLE syscad_app   LOGIN PASSWORD '1234_app';

CREATE SCHEMA preparation AUTHORIZATION syscad_owner;
CREATE SCHEMA publie      AUTHORIZATION syscad_owner;
CREATE SCHEMA journal     AUTHORIZATION syscad_owner;

GRANT CONNECT ON DATABASE syscad TO syscad_owner, syscad_app;
GRANT USAGE ON SCHEMA preparation, publie, journal TO syscad_app;

ALTER DEFAULT PRIVILEGES FOR ROLE syscad_owner IN SCHEMA preparation
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO syscad_app;
ALTER DEFAULT PRIVILEGES FOR ROLE syscad_owner IN SCHEMA publie
  GRANT SELECT, INSERT, UPDATE ON TABLES TO syscad_app;
ALTER DEFAULT PRIVILEGES FOR ROLE syscad_owner IN SCHEMA journal
  GRANT SELECT, INSERT ON TABLES TO syscad_app;
ALTER DEFAULT PRIVILEGES FOR ROLE syscad_owner
  GRANT USAGE, SELECT ON SEQUENCES TO syscad_app;